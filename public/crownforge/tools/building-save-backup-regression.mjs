import assert from 'node:assert/strict';
import { CrownforgeSimulation } from '../src/simulation.js';
import { BUILDING_ART_VERSION } from '../src/building-depth-data.js';
import { SAVE_KEY, BUILDING_BACKUP_KEY, readSavedGameForBuildingUpgrade, previousBuildingSave, restorePreviousBuildingSave } from '../src/building-save-backup.js';
const raw = '{ "version":1, "units":[], "buildings":[], "resources":{"gold":143} }';
function store() { const values=new Map([[SAVE_KEY,raw]]);return {values,getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v)}; }
const s=store();
assert.equal(readSavedGameForBuildingUpgrade(s).resources.gold,143);
assert.equal(s.getItem(SAVE_KEY),raw);
assert.equal(previousBuildingSave(s),raw);
readSavedGameForBuildingUpgrade(s);
assert.equal(s.values.size,3,'repeat loads do not duplicate or replace backup');
s.setItem(SAVE_KEY,'{"version":1,"units":[],"buildings":[],"resources":{"gold":77}}');
readSavedGameForBuildingUpgrade(s);
assert.equal(s.getItem(BUILDING_BACKUP_KEY),raw,'first backup is permanent');
assert.equal(JSON.parse(previousBuildingSave(s)).resources.gold,77,'another legacy save is separately preserved');
s.setItem(SAVE_KEY,'new running settlement');
assert(restorePreviousBuildingSave(s));
assert.equal(JSON.parse(s.getItem(SAVE_KEY)).resources.gold,77);
const denied=store();denied.setItem=()=>{throw Error('quota');};
assert.throws(()=>readSavedGameForBuildingUpgrade(denied));
assert.equal(denied.getItem(SAVE_KEY),raw,'backup failure cannot overwrite original');
const truncated=store();truncated.setItem=(k,v)=>truncated.values.set(k,v.slice(1));
assert.throws(()=>readSavedGameForBuildingUpgrade(truncated));
assert.equal(truncated.getItem(SAVE_KEY),raw,'failed byte verification leaves source unchanged');
const simulation=new CrownforgeSimulation({seed:42});
const legacy=simulation.createSaveSnapshot(); delete legacy.buildingArtVersion;
legacy.buildings.push({...legacy.buildings[0],id:999999,type:'house',x:79,z:82});
legacy.resources.gold=987; legacy.units[0].x=78; legacy.units[0].z=82;
const original=JSON.stringify(legacy), persistent=store();persistent.setItem(SAVE_KEY,original);
globalThis.localStorage=persistent;
assert(simulation.loadFromStorage());
assert.deepEqual(simulation.buildings.map(b=>[b.id,b.x,b.z]),legacy.buildings.map(b=>[b.id,b.x,b.z]),'load preserves saved building positions');
assert.deepEqual(simulation.units.map(u=>[u.id,u.x,u.z]),legacy.units.map(u=>[u.id,u.x,u.z]),'load preserves saved character positions');
assert.deepEqual(simulation.resourcesNodes.map(n=>[n.id,n.x,n.z,n.amount]),legacy.resourcesNodes.map(n=>[n.id,n.x,n.z,n.amount]),'load preserves resource sites and quantities');
assert.equal(simulation.resources.gold,987);assert.equal(persistent.getItem(SAVE_KEY),original);
assert.equal(previousBuildingSave(persistent),original);
assert(simulation.saveToStorage({silent:true}));
assert.equal(JSON.parse(persistent.getItem(SAVE_KEY)).buildingArtVersion,BUILDING_ART_VERSION);
assert.equal(previousBuildingSave(persistent),original,'ordinary saving preserves the older exact backup');
const saveFirst=store();globalThis.localStorage=saveFirst;
assert(simulation.saveToStorage({silent:true}));assert.equal(previousBuildingSave(saveFirst),raw,'saving before loading also protects an older save');
delete globalThis.localStorage;
console.log('building-save-backup-regression: passed');
